const tables: Record<Language, Strings> = { de, en };
/** The strings in effect. */
export let t: Strings = de;
/** The locale dates and numbers are written in. */
let locale = 'de-DE';

/**
 * Puts `language` into effect, before the first render. Dates and numbers take the browser's
 * variant of it (`en-GB` writes the day first), or the usual one. A browser on Linux with the
 * POSIX locale says `en-US@posix`, which `Intl` refuses: the page stayed blank on it.
 */
export function setLanguage(language: Language, preferred: readonly string[] = typeof navigator === 'undefined' ? [] : navigator.languages) {
  t = tables[language];
  locale = preferred.find((l) => languageOf(l) === language && validTag(l)) ?? (language === 'de' ? 'de-DE' : 'en-US');
  if (typeof document !== 'undefined') document.documentElement.lang = language;
}

function validTag(tag: string): boolean {
  try {
    return Intl.getCanonicalLocales(tag).length > 0;
  } catch {
    return false;
  }
}

/** The push-to-talk key as the owner reads it ("rechte Wahltaste" is "Wahltaste rechts", "Strg+Umschalt+Leertaste"). */
export function pushKeyLabel(key: string, mac = typeof navigator !== 'undefined' && /Mac/.test(navigator.platform)) {
  const k = t.config.pushKey.keys;
  const win = typeof navigator !== 'undefined' && /Win/.test(navigator.platform);
  const names: Record<string, string> = { Control: k.Control, Alt: mac ? k.Option : k.Alt, Shift: k.Shift, Meta: mac ? k.Command : win ? k.Windows : k.Super, Space: k.Space };
  return key
    .split('+')
    .map((part) => {
      const side = /(Left|Right)$/.exec(part)?.[1] as 'Left' | 'Right' | undefined;
      const name = side ? part.slice(0, -side.length) : part;
      const shown = names[name] ?? name.replace(/^Key|^Digit/, '');
      return side ? t.config.pushKey.side[side](shown) : shown;
    })
    .join('+');
}

/** A time of day, hours and minutes. */
export const clock = (d: Date | string | number) => new Date(d).toLocaleTimeString(locale, { hour: '2-digit', minute: '2-digit' });
/** A short date: day and month. */
export const shortDay = (d: Date | string | number) => new Date(d).toLocaleDateString(locale, { day: 'numeric', month: 'short' });
/** A long date with its weekday; the year only when it is not this one. */
const longDay = (d: Date, today: Date) =>
  d.toLocaleDateString(locale, { weekday: 'long', day: 'numeric', month: 'long', ...(d.getFullYear() === today.getFullYear() ? {} : { year: 'numeric' }) });
/** A number, with `digits` decimals at most. */
const number = (n: number, digits = 0) => n.toLocaleString(locale, { maximumFractionDigits: digits, minimumFractionDigits: digits });

export const stateLabel = (i: { state: CardState; need?: Need; queue?: Queue; idea?: Idea; question?: unknown; answering?: true; finishing?: boolean; followUp?: boolean; prototypeEnd?: 'discarded' | 'built' }) =>
  i.prototypeEnd
    ? t.idea.ended[i.prototypeEnd]
    : i.finishing && (i.state === 'live' || i.state === 'done')
    ? i.followUp
      ? i.state === 'done' ? t.followingUpDone : t.followingUp
      : i.state === 'done' ? t.finishingDone : t.finishing
    : i.idea
    ? i.idea.status === 'open' && i.idea.yourTurn && !i.idea.thinking
      ? t.idea.yourTurn
      : t.idea.status[i.idea.status]
    : i.queue
    ? 'checking' in i.queue
      ? t.queue.checking
      : 'cutting' in i.queue
        ? t.queue.cutting
        : 'workspace' in i.queue
          ? t.queue.workspace
          : t.queue.waiting
    : i.state === 'waiting' && i.need
      ? i.answering
        ? t.answering
        : i.need === 'demo' && i.question
          ? t.demoWithQuestion
          : t.need[i.need]
      : t.state[i.state];

/** The owner's text for a refused request or a logged error code; the generic one for anything unknown. */
export const errorText = (code: string | undefined) => (code && Object.hasOwn(t.error, code) ? t.error[code as ErrorCode] : t.error.invalid);
